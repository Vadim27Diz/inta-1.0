#!/usr/bin/env node
// Build CSS from Figma-shaped tokens JSON.
// Usage: node build-tokens.mjs <tokens.json> <out.css> [catalog.md]
// Input is either assets/tokens.seed.json or a Figma export made with references/figma.md → "Export".
import fs from "node:fs";

const [, , inFile, outFile, catalogFile] = process.argv;
if (!inFile || !outFile) {
  console.error("Usage: node build-tokens.mjs <tokens.json> <out.css> [catalog.md]");
  process.exit(1);
}
const data = JSON.parse(fs.readFileSync(inFile, "utf8"));
const P = data.prefix || "ds";
// name → the variable itself, not a copy. A copy carrying collection/modes tempts the rest of the
// file to read v.collection — which is undefined on the raw collection arrays, so the check silently
// passes and the filter below stops filtering. The collection is passed explicitly instead.
const byName = new Map();
for (const c of data.collections) for (const v of c.variables) byName.set(v.name, v);

// Figma name → token key. "color/primary/default" → "color-primary" (explicit default in Figma, truncated in code)
const key = (name) => name.replace(/\/default$/, "").replace(/\//g, "-").replace(/\./g, "-");
const cssVar = (name) => `--${P}-${key(name)}`;
// Tailwind name: theme colors drop the "color-" category because the utility (bg-, text-, border-) already says it
const twColor = (name) => key(name).replace(/^color-/, "");

const hex = (val) => {
  if (typeof val === "string") return val;
  const h = (x) => Math.round(x * 255).toString(16).padStart(2, "0").toUpperCase();
  const a = val.a === undefined || val.a === 1 ? "" : h(val.a);
  return `#${h(val.r)}${h(val.g)}${h(val.b)}${a}`;
};
const fontStack = (family, name) => {
  const fallback = /mono/.test(name) ? "ui-monospace, monospace" : /serif/i.test(family) && !/sans/i.test(family) ? "ui-serif, Georgia, serif" : "ui-sans-serif, system-ui, sans-serif";
  return `"${family}", ${fallback}`;
};
const rem = (px) => (px === 0 ? "0" : px >= 9999 ? "9999px" : `${+(px / 16).toFixed(4)}rem`);

function value(v, mode) {
  const raw = v.valuesByMode[mode];
  if (raw && typeof raw === "object" && "alias" in raw) {
    if (!byName.has(raw.alias)) throw new Error(`${v.name} [${mode}] aliases missing token ${raw.alias}`);
    return `var(${cssVar(raw.alias)})`;
  }
  if (v.type === "COLOR") return hex(raw);
  if (v.type === "STRING") return fontStack(raw, v.name);
  if (v.type === "FLOAT") return /weight/.test(v.name) ? String(raw) : rem(raw);
  return String(raw);
}

// Which primitives reach CSS: colors and fonts. Spacing, text sizes and weights stay Tailwind's own scale.
// Takes the collection name as an argument — never off the variable, which does not know its collection.
const emitted = (v, collection) => collection !== "Primitives" || v.type === "COLOR" || v.type === "STRING";

// Takes the whole collection so the name travels with the variables it filters.
const block = (selector, col, mode) =>
  `${selector} {\n${col.variables.filter((v) => emitted(v, col.name)).map((v) => `  ${cssVar(v.name)}: ${value(v, mode)};`).join("\n")}\n}\n`;

const col = (name) => data.collections.find((c) => c.name === name);
const out = [];
out.push(`/* GENERATED by build-tokens.mjs from ${inFile.split("/").pop()} — do not edit by hand. Change tokens in Figma, export, rebuild. */\n`);

const prim = col("Primitives");
out.push("/* Layer 1 — Primitives (never used by components directly) */\n" + block(":root", prim, prim.modes[0]));

const brand = col("Brand");
out.push("/* Layer 2 — Brand (white-label). Set data-brand on <html> or any wrapper. */");
brand.modes.forEach((m, i) => {
  const sel = `${i === 0 ? ":root, " : ""}[data-brand="${m.toLowerCase()}"]`;
  out.push(block(sel, brand, m));
});

// Theme + Component vars are re-declared on every [data-brand] scope so nested brand wrappers recompute them.
const theme = col("Theme");
out.push("/* Layer 3 — Theme (light/dark). Toggle with class=\"dark\". */");
out.push(block(":root, [data-brand]", theme, theme.modes[0]));
out.push(block(".dark, .dark [data-brand], [data-brand].dark", theme, theme.modes[1]));

const comp = col("Component");
if (comp) {
  out.push("/* Layer 4 — Component (object-level, aliases into Theme) */");
  out.push(block(":root, [data-brand], .dark", comp, comp.modes[0]));
}

// Tailwind v4 mapping
const tw = [];
tw.push("@theme {\n  --color-*: initial; /* removes the raw palette: bg-blue-500 no longer exists, only semantic colors */\n}\n");
tw.push("@theme inline {");
for (const v of theme.variables) if (v.type === "COLOR") tw.push(`  --color-${twColor(v.name)}: var(${cssVar(v.name)});`);
if (comp) for (const v of comp.variables) if (v.type === "COLOR") tw.push(`  --color-${twColor(v.name)}: var(${cssVar(v.name)});`);
for (const v of [...brand.variables, ...prim.variables]) {
  if (v.type === "STRING" && v.name.startsWith("font/")) tw.push(`  --font-${v.name.split("/")[1]}: var(${cssVar(v.name)});`);
}
// Brand radii override Tailwind's --radius-* scale, so rounded-lg follows the brand.
// Iterate Brand separately: these are the brand-scoped radii, not Primitives radius/none|full.
for (const v of brand.variables) {
  if (v.type === "FLOAT" && v.name.startsWith("radius/")) tw.push(`  --radius-${v.name.split("/")[1]}: var(${cssVar(v.name)});`);
}
tw.push("}\n");

// Text styles → one utility per style (typo-heading-1 …), mirrors Figma text styles 1:1
const num = (n) => prim.variables.find((v) => v.name === n)?.valuesByMode[prim.modes[0]];
for (const s of data.textStyles || []) {
  const fam = byName.get(s.fontFamily);
  tw.push(`@utility typo-${key(s.name)} {
  font-family: var(${cssVar(fam.name)});
  font-size: ${rem(num(s.fontSize))};
  line-height: ${rem(num(s.lineHeight))};
  font-weight: ${num(s.fontWeight)};
  letter-spacing: ${s.letterSpacingEm || 0}em;
}`);
}

fs.writeFileSync(outFile, out.join("\n") + "\n/* Tailwind v4 mapping */\n" + tw.join("\n") + "\n");
// Counted over the collections, the same way block() filters them — so the number matches the file.
const cssVarCount = data.collections.reduce((n, c) => n + c.variables.filter((v) => emitted(v, c.name)).length, 0);
console.log(`✓ ${outFile}: ${cssVarCount} CSS variables, ${(data.textStyles || []).length} text styles`);

if (catalogFile) {
  const rows = [];
  const usage = (name) => {
    const t = twColor(name);
    if (/^color-(on-|link)/.test(key(name)) || /\/on-/.test(name)) return `text-${t}`;
    if (/border|focus-ring/.test(name)) return /focus-ring/.test(name) ? `ring-${t}` : `border-${t}`;
    return `bg-${t}`;
  };
  for (const c of [theme, comp].filter(Boolean)) {
    rows.push(`\n## ${c.name}${c.modes.length > 1 ? ` (modes: ${c.modes.join(", ")})` : ""}\n`);
    rows.push(`| Figma variable | CSS variable | Tailwind class (typical) | ${c.modes.map((m) => `${m} →`).join(" | ")} | Purpose |`);
    rows.push(`|---|---|---|${c.modes.map(() => "---").join("|")}|---|`);
    for (const v of c.variables) {
      const vals = c.modes.map((m) => { const r = v.valuesByMode[m]; return r && r.alias ? `\`${r.alias}\`` : `\`${hex(r)}\``; });
      rows.push(`| \`${v.name}\` | \`${cssVar(v.name)}\` | \`${usage(v.name)}\` | ${vals.join(" | ")} | ${v.description || ""} |`);
    }
  }
  rows.push(`\n## Brand (modes: ${brand.modes.join(", ")})\n`);
  rows.push(`| Figma variable | CSS variable | ${brand.modes.join(" | ")} |`);
  rows.push(`|---|---|${brand.modes.map(() => "---").join("|")}|`);
  for (const v of brand.variables) rows.push(`| \`${v.name}\` | \`${cssVar(v.name)}\` | ${brand.modes.map((m) => { const r = v.valuesByMode[m]; return r && r.alias ? `\`${r.alias}\`` : `\`${r}\``; }).join(" | ")} |`);
  rows.push(`\n## Text styles\n\n| Figma text style | Class | Family | Size / line-height | Weight |\n|---|---|---|---|---|`);
  for (const s of data.textStyles || []) rows.push(`| \`${s.name}\` | \`typo-${key(s.name)}\` | \`${s.fontFamily}\` | ${num(s.fontSize)}/${num(s.lineHeight)}px | ${num(s.fontWeight)} |`);
  fs.writeFileSync(catalogFile, `# Token catalog (generated)\n\nGenerated from \`${inFile.split("/").pop()}\` by \`scripts/build-tokens.mjs\`. Primitives are not listed: components must never use them.\n` + rows.join("\n") + "\n");
  console.log(`✓ ${catalogFile}`);
}
